"""Bundles web/ into worker/assets.js and deploys the Worker through the Cloudflare API. Secrets are read at runtime
from secrets/ and sent only to Cloudflare; nothing secret is printed."""
import base64, json, os, secrets as pysecrets, stat, sys, time, uuid
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cf
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "agent"))
from envfile import read_env

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAME = "aldia"
ENV = "/home/agent/agent/secrets/aldia_worker.env"
# Our other wallets, excluded from the outside-payer count. Outside the public repo; the deploy refuses to run without it.
EXTRA_OURS = os.path.join(os.path.dirname(ROOT), "private", "aldia_extra_ours.txt")
MODULES = ["worker.js", "assets.js", "pages.js", "rent.mjs", "outside.js", "probar.js", "eip55.js"]
TYPES = {".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8",
         ".svg": "image/svg+xml", ".png": "image/png", ".json": "application/json; charset=utf-8", ".mp4": "video/mp4"}


def agent_token():
    if not os.path.exists(ENV):
        fd = os.open(ENV, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w") as f:
            f.write("AGENT_TOKEN=" + pysecrets.token_hex(32) + "\n")
    return read_env(ENV, "AGENT_TOKEN")


def namespace():
    c, d = cf.api("GET", f"/accounts/{cf.ACCOUNT}/storage/kv/namespaces?per_page=100")
    for ns in d.get("result", []):
        if ns["title"] == "aldia":
            return ns["id"]
    c, d = cf.api("POST", f"/accounts/{cf.ACCOUNT}/storage/kv/namespaces", {"title": "aldia"})
    if not d.get("success"):
        sys.exit("cannot create KV namespace: " + str(d.get("errors"))[:200])
    return d["result"]["id"]


def bundle():
    assets = {}
    for fn in sorted(os.listdir(os.path.join(ROOT, "web"))):
        p = os.path.join(ROOT, "web", fn)
        ext = os.path.splitext(fn)[1]
        if ext not in TYPES or not os.path.isfile(p):
            continue
        if ext in (".png", ".mp4"):
            assets["/" + fn] = {"type": TYPES[ext], "b64": base64.b64encode(open(p, "rb").read()).decode()}
        else:
            assets["/" + fn] = {"type": TYPES[ext], "text": open(p, encoding="utf-8").read()}
    assets["/agent.json"] = {"type": TYPES[".json"], "text": open(os.path.join(ROOT, "agent.json"), encoding="utf-8").read()}
    src = "// generated by ops/deploy_worker.py\nexport const ASSETS = " + json.dumps(assets, ensure_ascii=False) + ";\n"
    open(os.path.join(ROOT, "worker", "assets.js"), "w", encoding="utf-8").write(src)
    # The Worker renders pages with the very same rent arithmetic the browser runs, as an ES module.
    rent = "// generated by ops/deploy_worker.py from web/rent.js\n" + open(os.path.join(ROOT, "web", "rent.js"), encoding="utf-8").read() \
        + "\nexport const AlDiaRent = globalThis.AlDiaRent;\n"
    open(os.path.join(ROOT, "worker", "rent.mjs"), "w", encoding="utf-8").write(rent)
    return src


def extra_ours():
    import re
    if not os.path.exists(EXTRA_OURS):
        sys.exit("missing " + EXTRA_OURS + ": the outside-payer check would not know our other wallets")
    addrs = [l.strip().lower() for l in open(EXTRA_OURS, encoding="utf-8") if re.fullmatch(r"0x[0-9a-fA-F]{40}", l.strip())]
    if not addrs:
        sys.exit("no addresses in " + EXTRA_OURS)
    return ",".join(addrs)


def main():
    assets_src = bundle()
    srcs = {m: open(os.path.join(ROOT, "worker", m), encoding="utf-8").read() for m in MODULES if m != "assets.js"}
    srcs["assets.js"] = assets_src
    if "--bundle-only" in sys.argv:
        print("bundled", len(assets_src))
        return
    extra = extra_ours()
    ns = namespace()
    meta = {"main_module": "worker.js", "compatibility_date": "2026-01-15",
            "bindings": [{"type": "kv_namespace", "name": "KV", "namespace_id": ns},
                         {"type": "secret_text", "name": "AGENT_TOKEN", "text": agent_token()},
                         {"type": "secret_text", "name": "EXTRA_OURS", "text": extra}]}
    b = "----aldia" + uuid.uuid4().hex
    def part(name, filename, ctype, body):
        head = f'--{b}\r\nContent-Disposition: form-data; name="{name}"' + (f'; filename="{filename}"' if filename else "") + f"\r\nContent-Type: {ctype}\r\n\r\n"
        return head.encode() + body.encode() + b"\r\n"
    raw = part("metadata", None, "application/json", json.dumps(meta)) \
        + b"".join(part(m, m, "application/javascript+module", srcs[m]) for m in MODULES) + f"--{b}--\r\n".encode()
    print("modules", ", ".join(MODULES), "excluded wallets", len(extra.split(",")) + 2)
    c, d = cf.api("PUT", f"/accounts/{cf.ACCOUNT}/workers/scripts/{NAME}", raw=raw,
                  headers={"content-type": f"multipart/form-data; boundary={b}"}, timeout=120)
    print("upload", c, d.get("success"), [e.get("message") for e in d.get("errors", [])][:3])
    if not d.get("success"):
        sys.exit(1)
    c, d = cf.api("POST", f"/accounts/{cf.ACCOUNT}/workers/scripts/{NAME}/subdomain", {"enabled": True, "previews_enabled": False})
    print("subdomain", c, d.get("success"))
    print("https://aldia.swiftbotlab.workers.dev bundle bytes", len(assets_src))


if __name__ == "__main__":
    main()
